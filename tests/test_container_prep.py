TESTED_DOCKERFILE = """FROM python:3.12-slim

ENV PYTHONUNBUFFERED=1 \\
    PYTHONDONTWRITEBYTECODE=1 \\
    HOME=/home/hobees \\
    UV_TOOL_DIR=/opt/uv-tools \\
    UV_TOOL_BIN_DIR=/usr/local/bin

# 1. Install uv system-wide as root
RUN pip install --no-cache-dir uv

# 2. Create non-root user and directories
RUN groupadd --system --gid 1000 hobees \\
    && useradd --system --uid 1000 --gid hobees --home-dir ${HOME} --create-home hobees \\
    && mkdir -p ${HOME}/output ${HOME}/skills ${HOME}/config /opt/uv-tools \\
    && chown -R hobees:hobees ${HOME} /opt/uv-tools

# 3. Install hobees into /opt/uv-tools with symlink in /usr/local/bin
RUN uv tool install hobees && chmod -R a+rX /opt/uv-tools ${HOME}

# 4. Copy default config and entrypoint
COPY --chown=hobees:hobees hobees.yaml ${HOME}/config/hobees.yaml
COPY --chown=hobees:hobees docker-entrypoint.sh /entrypoint.sh
RUN chmod +x /entrypoint.sh

USER hobees
WORKDIR ${HOME}

ENTRYPOINT ["/entrypoint.sh"]
"""

TESTED_ENTRYPOINT = """#!/bin/sh
set -eu

# The exit code is what a pipeline reads: 0 completed, 1 failed, 2 stopped for an
# approval a headless run cannot answer. `set -eu` and `exec` keep it intact, so
# nothing between hobees and the container exit code can swallow it.

HOME_DIR="${HOME:-/home/hobees}"
CONFIG="${HOBEES_CONFIG_PATH:-${HOME_DIR}/config/hobees.yaml}"
GOAL="${HOBEES_GOAL_FILE:-${HOME_DIR}/goal.txt}"
HIVE="${HOBEES_RUN_HIVE:-}"

# 1. Initialize hobees with the configuration copied into the image.
if [ -f "$CONFIG" ]; then
  hobees init --config "$CONFIG"
fi

# 2. Container args override the default command.
if [ "$#" -gt 0 ]; then
  exec hobees "$@"
fi

# 3. Build positional arguments for `hobees run` (dash-compatible, no bash arrays).
set --
if [ -n "$HIVE" ]; then
  set -- --hive "$HIVE"
fi

# 4. Run the goal from file if mounted; otherwise read from stdin.
if [ -f "$GOAL" ]; then
  exec hobees run "$@" --json "$(cat "$GOAL")"
fi
exec hobees run "$@" - --json
"""

TESTED_ENV = """# Host UID/GID mapping
HOBEES_UID=1000
HOBEES_GID=1000

# Postgres credentials
POSTGRES_DB=hobeesdb
POSTGRES_USER=hobees
POSTGRES_PASSWORD=hello

# Hobees runtime configuration
HOBEES_RUN_HIVE=Poets
HOBEES_ARTIFACTS_ROOT=/home/hobees/output
HOBEES_SKILLS_DIR=/home/hobees/skills
HOBEES_CONFIG_PATH=/home/hobees/config/hobees.yaml
HOBEES_GOAL_FILE=/home/hobees/goal.txt
"""


def reference_spec() -> container_prep.ContainerSpec:
    """The inputs the tested files were written with: one field per value, the rest defaults."""
    return container_prep.ContainerSpec(
        container_name="myfuncontainer",
        profiles=["poets"],
        goal="Write a fun poem about sun",
        run_hive="Poets",
    )


def test_the_generated_files_match_the_tested_set():
    """With the same field values, the generator reproduces the files that actually run."""
    spec = reference_spec()
    assert container_prep.compose_yaml(spec).strip() == TESTED_COMPOSE.strip()
    assert container_prep.dockerfile_text(spec).strip() == TESTED_DOCKERFILE.strip()
    assert container_prep.entrypoint_text(spec).strip() == TESTED_ENTRYPOINT.strip()

    sample = container_prep.env_sample_text(spec)
    # Same sections and the same order as the .env the tested set runs with; the header says
    # the file is a checklist, and no value is filled in for a secret.
    body = "\n".join(sample.split("\n")[4:])
    assert body.strip() == TESTED_ENV.strip().replace("hello", "")


def test_compose_yaml_keeps_environment_names_not_values():
    spec = reference_spec()
    parsed = yaml.safe_load(container_prep.compose_yaml(spec))
    service = parsed["services"]["hobees"]

    assert service["container_name"] == "myfuncontainer"
    assert socket.gethostname() not in container_prep.compose_yaml(spec)
    assert "hello" not in container_prep.compose_yaml(spec)
    assert "sk-" not in container_prep.compose_yaml(spec)
    assert service["profiles"] == ["poets"]
    # The Postgres password has no default, so a run without it fails with a message
    # instead of connecting to a database nobody configured.
    assert "${POSTGRES_PASSWORD:?error}" in service["environment"]["HOBEES_DATABASE_URL"]
    assert service["depends_on"]["postgres"]["condition"] == "service_healthy"
    # Postgres data is a named Docker volume, declared in the top-level block at the bottom
    # of the file: init-dirs has no host folder to create for it.
    assert parsed["services"]["postgres"]["volumes"] == ["postgres_data:/var/lib/postgresql/data"]
    assert parsed["volumes"] == {"postgres_data": None}
    assert service["volumes"][-1] == "./goal.txt:/home/hobees/goal.txt:ro"
    # Nothing is baked as a default command: the entrypoint script decides what runs.
    assert "command" not in service
    assert "entrypoint" not in service
    assert service["restart"] == "no"
    assert service["extra_hosts"] == ["host.docker.internal:host-gateway"]


def test_init_dirs_prepares_the_mounted_folders_before_anything_runs():
    parsed = yaml.safe_load(container_prep.compose_yaml(reference_spec()))
    init = parsed["services"]["init-dirs"]

    # The goal is a file mount, so it is not created as a folder, and a named volume has no
    # host folder either.
    assert init["command"][2].strip() == (
        "mkdir -p /workspace/output /workspace/skills &&\n"
        "chown -R ${HOBEES_UID:-1000}:${HOBEES_GID:-1000} "
        "/workspace/output /workspace/skills"
    )
    assert init["user"] == "0:0"
    assert init["volumes"] == [".:/workspace"]
    assert parsed["services"]["hobees"]["depends_on"]["init-dirs"] == {"condition": "service_completed_successfully"}
    assert parsed["services"]["postgres"]["depends_on"]["init-dirs"] == {"condition": "service_completed_successfully"}

    # Only the folders the compose file bind-mounts, in mount order.
    typed = container_prep.ContainerSpec(goal="x", volumes=["./cache:/home/hobees/cache", "./skills:/home/hobees/skills"])
    assert typed.host_dirs() == ["cache", "skills"]
    assert typed.named_volumes() == ["postgres_data"]
    # A volume typed as a host folder is still prepared by init-dirs.
    bind = container_prep.ContainerSpec(goal="x", db_volume="./pgdata")
    assert bind.host_dirs() == ["output", "skills", "pgdata"]
    assert bind.named_volumes() == []
    # A named volume has no host folder to create, so the service is not needed at all.
    named = container_prep.ContainerSpec(goal="x", volumes=["artifacts:/data/artifacts"], include_db=False)
    assert named.host_dirs() == []
    assert "init-dirs" not in yaml.safe_load(container_prep.compose_yaml(named))["services"]


def test_named_volumes_are_declared_at_the_bottom_of_the_file():
    text = container_prep.compose_yaml(reference_spec())
    parsed = yaml.safe_load(text)

    # The block is the last thing in the file, after the commented-out web service.
    assert text.rstrip().endswith("volumes:\n  postgres_data:")
    assert parsed["volumes"] == {"postgres_data": None}

    # Names appear in the order the services mount them, once each.
    both = container_prep.ContainerSpec(
        goal="x", volumes=["artifacts:/data/artifacts", "./skills:/home/hobees/skills", "artifacts:/data/scratch"]
    )
    assert both.named_volumes() == ["artifacts", "postgres_data"]
    assert container_prep.volumes_block(both).split("\n") == ["volumes:", "  artifacts:", "  postgres_data:"]

    # A file that only bind-mounts host folders needs no top-level block.
    bind_only = container_prep.ContainerSpec(goal="x", include_db=False)
    assert bind_only.named_volumes() == []
    assert container_prep.volumes_block(bind_only) == ""
    _, warnings = container_prep.validate_compose(container_prep.compose_yaml(bind_only))
    assert not warnings

    # A volume mounted without being declared is reported.
    _, warnings = container_prep.validate_compose(
        "services:\n  app:\n    image: app\n    volumes:\n      - pgdata:/var/lib/postgresql/data\n"
    )
    assert any("not declared" in warning for warning in warnings)


def test_default_spec_uses_the_current_settings(tmp_path, monkeypatch):
    root = tmp_path / "project"
    root.mkdir()
    monkeypatch.setenv("HOBEES_PROJECT_ROOT", str(root))

    spec = container_prep.default_spec(["NONE", "GEMINI_API_KEY"])
    # Generated files hold relative paths only - a path from the author's machine would make
    # the file unusable for anyone else.
    assert spec.resolved_volumes() == [
        "./output:/home/hobees/output",
        "./skills:/home/hobees/skills",
        "./goal.txt:/home/hobees/goal.txt:ro",
    ]
    assert str(tmp_path) not in container_prep.compose_yaml(spec)
    assert "C:/" not in container_prep.compose_yaml(spec)
    assert spec.api_key_envs == ["GEMINI_API_KEY"]
    assert spec.ports == ["6543:6543"]
    assert any("no goal set" in warning for warning in spec.warnings())
    assert not any("valid compose service key" in warning for warning in spec.warnings())
    # The ids baked into the image are the defaults .env maps the host user onto.
    assert spec.uid() == container_prep.DEFAULT_UID == 1000
    assert spec.gid() == container_prep.DEFAULT_GID == 1000


def test_bake_mode_copies_the_goal_into_the_image():
    spec = container_prep.ContainerSpec(goal="Review src/", goal_mode="bake", run_hive="dev-team")
    dockerfile = container_prep.dockerfile_text(spec)
    volumes = spec.resolved_volumes()

    assert "COPY --chown=hobees:hobees goal.txt ${HOME}/goal.txt" in dockerfile
    assert "./goal.txt:/home/hobees/goal.txt:ro" not in volumes
    assert spec.goal_mode in container_prep.GOAL_MODES

    # stdin mode has no file to mount or bake: the goal arrives through the pipe.
    stdin_spec = container_prep.ContainerSpec(goal_mode="stdin")
    assert stdin_spec.pipeline_command() == ["run", "-", "--json"]
    assert stdin_spec.resolved_command() == []  # an override only
    assert "./goal.txt:/home/hobees/goal.txt:ro" not in stdin_spec.resolved_volumes()
    assert "COPY --chown=hobees:hobees goal.txt" not in container_prep.dockerfile_text(stdin_spec)


def test_entrypoint_initialises_then_runs_the_goal():
    spec = container_prep.ContainerSpec(run_hive="dev-team", goal="`whoami` in the prompt; $(id)")
    script = container_prep.entrypoint_text(spec)

    assert script.startswith("#!/bin/sh")
    assert 'set -eu' in script
    assert "hobees init --config" in script
    assert 'exec hobees "$@"' in script
    # The script runs the goal as data quoted from the file, not as shell built from it.
    assert '"$(cat "$GOAL")"' in script
    assert "${HOBEES_RUN_HIVE:-}" in script
    # The prompt text is never written into the script: a goal cannot be read as shell.
    assert "whoami" not in script
    assert "$(id)" not in script
    assert spec.goal not in script

    # The checkbox is honoured: without init the script goes straight to the goal.
    without_init = container_prep.ContainerSpec(goal="x", run_init=False)
    script = container_prep.entrypoint_text(without_init)
    assert "hobees init --config" not in script
    assert "# 1. Container args override" in script


def test_dockerfile_follows_the_tested_image_and_installs_from_pypi():
    text = container_prep.dockerfile_text(container_prep.ContainerSpec(goal="x"))
    assert text.startswith("FROM python:3.12-slim")
    # In operation hobees is installed with `uv tool install`, so the image has no source tree.
    assert "RUN uv tool install hobees" in text
    assert "COPY src" not in text
    assert "uv sync" not in text
    assert "RUN pip install --no-cache-dir uv" in text
    assert "USER hobees" in text
    # The user, its home folders and the tools dir are created while still root.
    assert text.index("groupadd") < text.index("COPY --chown=hobees:hobees") < text.index("USER hobees")
    assert "UV_TOOL_DIR=/opt/uv-tools" in text
    assert f'ENTRYPOINT ["{container_prep.CONTAINER_ENTRYPOINT}"]' in text
    assert text.count(chr(92)) >= 3  # the RUN continuation lines stay one instruction
    assert "COPY --chown=hobees:hobees hobees.yaml ${HOME}/config/hobees.yaml" in text
    assert "COPY --chown=hobees:hobees docker-entrypoint.sh /entrypoint.sh" in text

    # No CMD on purpose: the script decides, and args passed to `docker compose run` override it.
    assert "CMD [" not in text
    assert container_prep.ContainerSpec(goal="x").resolved_command() == []
    override = container_prep.ContainerSpec(goal="x", command=["run", "-"])
    assert yaml.safe_load(container_prep.compose_yaml(override))["services"]["hobees"]["command"] == ["run", "-"]

    # A different base image changes only the FROM line, not the shape of the image.
    alt = container_prep.dockerfile_text(container_prep.ContainerSpec(goal="x", base_image="python:3.13-slim"))
    assert alt.startswith("FROM python:3.13-slim")
    assert "COPY --chown=hobees:hobees hobees.yaml" in alt


def test_the_paths_are_defined_once_in_the_script_and_read_from_env():
    spec = reference_spec()
    compose = yaml.safe_load(container_prep.compose_yaml(spec))["services"]["hobees"]
    dockerfile = container_prep.dockerfile_text(spec)
    script = container_prep.entrypoint_text(spec)

    # The compose file only carries names; .env supplies the values, including the paths.
    assert compose["environment"] == {"HOBEES_DATABASE_URL": spec.db_url()}
    assert "HOBEES_CONFIG_PATH" not in compose["environment"]
    assert "${HOME_DIR}/config/hobees.yaml" in script
    assert "${HOME_DIR}/goal.txt" in script
    sample = container_prep.env_sample_text(spec)
    for path in ("HOBEES_CONFIG_PATH", "HOBEES_GOAL_FILE", "HOBEES_ARTIFACTS_ROOT", "HOBEES_SKILLS_DIR"):
        assert path in sample

    # stdin mode has no goal file, so the script only reads the pipe.
    stdin = container_prep.ContainerSpec(goal_mode="stdin", goal="piped")
    assert "$(cat" not in container_prep.entrypoint_text(stdin)
    assert 'exec hobees run "$@" - --json' in container_prep.entrypoint_text(stdin)
    assert "stdin mode: the goal is piped" in container_prep.env_sample_text(stdin)


def test_the_run_command_follows_the_profile_and_the_service():
    spec = reference_spec()
    profiles = " ".join(f"--profile {profile}" for profile in spec.profiles)
    command = f"docker compose {profiles} run --rm {spec.service}"
    assert command == "docker compose --profile poets run --rm hobees"

    # Args typed in the field come after the service key, and stdin needs -T to be readable.
    both = container_prep.ContainerSpec(profiles=["poets", "ui"], goal="x")
    assert " ".join(f"--profile {p}" for p in both.profiles) == "--profile poets --profile ui"
    pipe = container_prep.ContainerSpec(profiles=["poets"], goal_mode="stdin", goal="piped")
    assert "run -T --rm hobees" in f"docker compose --profile poets run -T --rm {pipe.service}"
    no_profile = container_prep.ContainerSpec(goal="x", profiles=[])
    assert any("profiles" in warning for warning in no_profile.warnings())


